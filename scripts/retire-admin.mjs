import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const [version,replacement]=process.argv.slice(2);
if(!/^v\d+\.\d+\.\d+$/.test(version||'')||!/^v\d+\.\d+\.\d+$/.test(replacement||'')||version===replacement)throw Error('请提供不同的旧版本与替代版本。');
const dir=path.join(root,'versions',version),next=path.join(root,'versions',replacement);
await fs.access(path.join(next,'vault/manifest.bin'));
const archive=path.join(root,'.artifacts',version,'zhuji-'+version+'-admin.zip');
if((await fs.stat(archive)).size<1)throw Error('需先保留本机管理员历史归档。');
for(const name of ['vault','admin','access.js','access.css','SHA256SUMS'])await fs.rm(path.join(dir,name),{force:true,recursive:true});
const target='../'+replacement+'/';
await fs.writeFile(path.join(dir,'index.html'),'<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>住记 · 管理员入口已更新</title></head><body><p>此版本管理员线上入口已停用。<a href="'+target+'">打开当前住记</a></p><script>location.replace('+JSON.stringify(target)+'+location.search+location.hash)</script></body></html>\n');
const info={version,status:'admin-retired',replacement,publicPath:'./aluminum/',originalTagPreserved:true,retiredAt:new Date().toISOString()};
await fs.writeFile(path.join(dir,'release.json'),JSON.stringify(info,null,2)+'\n');
await fs.writeFile(path.join(dir,'README.txt'),'管理员线上入口和密文已因口令轮换停用。当前版本：'+replacement+'。\n本版本铝型材公开设计仍位于aluminum/。原标签与本机归档保留，已下载或Git历史中的副本无法撤回。\n');
const indexFile=path.join(root,'releases.json'),index=JSON.parse(await fs.readFile(indexFile,'utf8'));
index.releases=index.releases.map(r=>r.version===version?{...r,adminRetired:true,replacement}:r);
await fs.writeFile(indexFile,JSON.stringify(index,null,2)+'\n');
console.log(JSON.stringify({version,adminOnline:'retired',replacement,publicDesign:'preserved',localArchive:archive}));
